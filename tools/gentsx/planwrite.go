func writePlanGo(root string, setters map[string]*setter, bags map[string]*bagInfo, verbs []verb) error {
	names := make([]string, 0, len(bags))
	for n := range bags {
		names = append(names, n)
	}
	sort.Strings(names)

	kindToBag := map[string]string{}
	for _, b := range bags {
		kind := jsIdent(strings.TrimSuffix(b.iface, "Option"))
		kindToBag[kind] = b.tsName
	}

	fieldsByBag := map[string][]*setter{}
	for _, s := range setters {
		for bag := range s.actionBags {
			fieldsByBag[bag] = append(fieldsByBag[bag], s)
		}
	}

	refs := map[string][]string{}
	for _, name := range names {
		refs[name] = decodeRefs(fieldsByBag[name], kindToBag)
	}
	reachable := reachableBags(verbs, refs, handwrittenDecoderRoots(root))

	usedPkgs := map[string]bool{}
	for _, name := range names {
		if !reachable[name] {
			continue
		}
		for _, s := range fieldsByBag[name] {
			if s.jsonSkip && !s.nested {
				continue
			}
			for _, p := range s.goParams {
				if i := strings.Index(p.goType, "."); i > 0 {
					usedPkgs[p.goType[:i]] = true
				}
			}
		}
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by go run ./tools/gentsx; DO NOT EDIT.\n\n")
	buf.WriteString("package kit\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n")
	buf.WriteString("\t\"fmt\"\n")
	if len(usedPkgs) > 0 {
		buf.WriteString("\n")
		pkgs := make([]string, 0, len(usedPkgs))
		for p := range usedPkgs {
			pkgs = append(pkgs, p)
		}
		sort.Strings(pkgs)
		for _, p := range pkgs {
			if p == "time" || p == "json" || p == "ocispec" {
				continue
			}
			fmt.Fprintf(&buf, "\t%q\n", "github.com/aptd3v/containerkit/pkg/"+p)
		}
	}
	buf.WriteString(")\n\n")

	for _, name := range names {
		if !reachable[name] {
			continue
		}
		b := bags[name]
		writeDecodeFn(&buf, b, fieldsByBag[name], kindToBag)
	}

	writeDecodeAction(&buf, verbs)
	writeExec(&buf, verbs)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		_ = os.WriteFile(filepath.Join(root, "pkg", "kit", "tsx_plan_gen.go.bad"), buf.Bytes(), 0o644)
		return fmt.Errorf("gofmt tsx_plan_gen.go: %w", err)
	}
	out := filepath.Join(root, "pkg", "kit", "tsx_plan_gen.go")
	if err := os.WriteFile(out, formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s\n", out)
	return nil
}

// decodeRefs lists the nested decoders writeDecodeField emits for this bag.
func decodeRefs(fields []*setter, kindToBag map[string]string) []string {
	var out []string
	seen := map[string]bool{}
	for _, s := range fields {
		if s == nil || !s.nested {
			continue
		}
		key, _, ok := bagField(s, kindToBag)
		if !ok || key == "" || seen[key] {
			continue
		}
		seen[key] = true
		bag := ""
		if s.nestedIface != "" {
			bag = bagTSName(s.nestedIface)
		}
		if bag == "" {
			bag = kindToBag[s.propScope]
		}
		if bag == "" {
			bag = exportedIdent(s.kind) + "Options"
		}
		out = append(out, bag)
	}
	return out
}

var decodeCall = regexp.MustCompile(`\bdecode([A-Z][A-Za-z]*)\(`)

// handwrittenDecoderRoots finds decode functions called from kit sources
// other than the generated plan file. Connect and Up are two of those.
func handwrittenDecoderRoots(root string) []string {
	dir := filepath.Join(root, "pkg", "kit")
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	var names []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || name == "tsx_plan_gen.go" {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			continue
		}
		for _, m := range decodeCall.FindAllSubmatch(b, -1) {
			names = append(names, string(m[1]))
		}
	}
	return names
}

// reachableBags is the set of decoders a plan action, a nested field, or
// handwritten kit code can call.
func reachableBags(verbs []verb, refs map[string][]string, extra []string) map[string]bool {
	reachable := map[string]bool{}
	var stack []string
	for _, v := range verbs {
		if v.bag != "" {
			stack = append(stack, v.bag)
		}
	}
	stack = append(stack, extra...)
	for len(stack) > 0 {
		n := stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		if reachable[n] {
			continue
		}
		reachable[n] = true
		stack = append(stack, refs[n]...)
	}
	return reachable
}

func writeDecodeFn(buf *bytes.Buffer, b *bagInfo, fields []*setter, kindToBag map[string]string) {
	sort.Slice(fields, func(i, j int) bool { return fields[i].name < fields[j].name })
	fmt.Fprintf(buf, "func decode%s(v any) ([]%s, error) {\n", b.tsName, b.iface)
	buf.WriteString("\tif v == nil {\n\t\treturn nil, nil\n\t}\n")
	serial := 0
	for _, s := range fields {
		if s.jsonSkip && !s.nested {
			continue
		}
		key, _, ok := bagField(s, kindToBag)
		if ok && key != "" {
			serial++
		}
	}
	if serial == 0 {
		buf.WriteString("\t_, err := asObject(v)\n")
		buf.WriteString("\treturn nil, err\n")
		buf.WriteString("}\n\n")
		return
	}
	buf.WriteString("\tm, err := asObject(v)\n")
	buf.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	fmt.Fprintf(buf, "\tvar opts []%s\n", b.iface)
	buf.WriteString("\tvar errs []error\n")
	seen := map[string]bool{}
	for _, s := range fields {
		if s.jsonSkip && !s.nested {
			continue
		}
		key, _, ok := bagField(s, kindToBag)
		if !ok || key == "" || seen[key] {
			continue
		}
		seen[key] = true
		writeDecodeField(buf, s, key, kindToBag)
	}
	buf.WriteString("\treturn opts, join(errs...)\n")
	buf.WriteString("}\n\n")
}

func writeDecodeField(buf *bytes.Buffer, s *setter, key string, kindToBag map[string]string) {
	fmt.Fprintf(buf, "\tif raw, ok := m[%q]; ok {\n", key)
	switch {
	case s.nested:
		bag := ""
		if s.nestedIface != "" {
			bag = bagTSName(s.nestedIface)
		}
		if bag == "" {
			bag = kindToBag[s.propScope]
		}
		if bag == "" {
			bag = exportedIdent(s.kind) + "Options"
		}
		if s.prop != "" {
			buf.WriteString("\t\titems, err := asObjectList(raw)\n")
			buf.WriteString("\t\tif err != nil {\n")
			fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", key+": %w")
			buf.WriteString("\t\t} else {\n")
			buf.WriteString("\t\t\tfor _, it := range items {\n")
			fmt.Fprintf(buf, "\t\t\t\tinner, err := decode%s(it)\n", bag)
			buf.WriteString("\t\t\t\tif err != nil {\n")
			fmt.Fprintf(buf, "\t\t\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", key+": %w")
			buf.WriteString("\t\t\t\t\tcontinue\n")
			buf.WriteString("\t\t\t\t}\n")
			leadParam := goParam{goType: "string", tsType: "string"}
			if len(s.goParams) > 0 {
				leadParam = s.goParams[0]
			}
			writeConvertAssign(buf, "\t\t\t\t", "lead", "it[\""+s.prop+"\"]", key, leadParam)
			fmt.Fprintf(buf, "\t\t\t\topts = append(opts, %s(lead, inner...))\n", s.name)
			buf.WriteString("\t\t\t}\n")
			buf.WriteString("\t\t}\n")
		} else {
			fmt.Fprintf(buf, "\t\tinner, err := decode%s(raw)\n", bag)
			buf.WriteString("\t\tif err != nil {\n")
			fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", key+": %w")
			buf.WriteString("\t\t} else {\n")
			fmt.Fprintf(buf, "\t\t\topts = append(opts, %s(inner...))\n", s.name)
			buf.WriteString("\t\t}\n")
		}
	case s.leaf:
		buf.WriteString("\t\titems, err := asObjectList(raw)\n")
		buf.WriteString("\t\tif err != nil {\n")
		fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", key+": %w")
		buf.WriteString("\t\t} else {\n")
		buf.WriteString("\t\t\tfor _, it := range items {\n")
		writeLeafCall(buf, s, key)
		buf.WriteString("\t\t\t}\n")
		buf.WriteString("\t\t}\n")
	case len(s.goParams) == 0:
		buf.WriteString("\t\ton, err := asBool(raw)\n")
		buf.WriteString("\t\tif err != nil {\n")
		fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", key+": %w")
		buf.WriteString("\t\t} else if on {\n")
		fmt.Fprintf(buf, "\t\t\topts = append(opts, %s())\n", s.name)
		buf.WriteString("\t\t}\n")
	default:
		writeScalarCall(buf, s, "raw")
	}
	buf.WriteString("\t}\n")
}

func writeLeafCall(buf *bytes.Buffer, s *setter, key string) {
	args := make([]string, 0, len(s.goParams))
	for i, p := range s.goParams {
		field := p.name
		if field == "" {
			field = "value"
		}
		src := fmt.Sprintf("it[%q]", field)
		if field == "name" {
			src = `firstKey(it, "name", "key")`
		}
		dst := fmt.Sprintf("a%d", i)
		writeConvertAssign(buf, "\t\t\t\t", dst, src, key, p)
		if p.variadic {
			args = append(args, dst+"...")
		} else {
			args = append(args, dst)
		}
	}
	fmt.Fprintf(buf, "\t\t\t\topts = append(opts, %s(%s))\n", s.name, strings.Join(args, ", "))
}

func writeConvertAssign(buf *bytes.Buffer, indent, dst, src, key string, p goParam) {
	fail := indent + "if err != nil {\n" +
		indent + "\terrs = append(errs, fmt.Errorf(%q, err))\n" +
		indent + "\tcontinue\n" +
		indent + "}\n"
	label := key + ": %w"
	switch {
	case p.variadic && p.goType == "Proto":
		ss := dst + "s"
		fmt.Fprintf(buf, "%s%s, err := asStringSlice(%s)\n", indent, ss, src)
		fmt.Fprintf(buf, fail, label)
		fmt.Fprintf(buf, "%s%s := protoSlice(%s)\n", indent, dst, ss)
	case p.variadic:
		fmt.Fprintf(buf, "%s%s, err := asStringSlice(%s)\n", indent, dst, src)
		fmt.Fprintf(buf, fail, label)
	case p.goType == "bool" || p.tsType == "boolean":
		fmt.Fprintf(buf, "%s%s, err := asBool(%s)\n", indent, dst, src)
		fmt.Fprintf(buf, fail, label)
	case p.goType == "time.Duration":
		fmt.Fprintf(buf, "%s%s, err := asDuration(%s)\n", indent, dst, src)
		fmt.Fprintf(buf, fail, label)
	case strings.Contains(p.tsType, "number") || isIntGoType(p.goType):
		raw := dst
		if intCast(p.goType, dst) != dst {
			raw = dst + "n"
		}
		fmt.Fprintf(buf, "%s%s, err := asInt(%s)\n", indent, raw, src)
		fmt.Fprintf(buf, fail, label)
		fmt.Fprintf(buf, "%sif err := fitInt(%s, %q); err != nil {\n", indent, raw, p.goType)
		fmt.Fprintf(buf, "%s\terrs = append(errs, fmt.Errorf(%q, err))\n", indent, label)
		fmt.Fprintf(buf, "%s\tcontinue\n%s}\n", indent, indent)
		if raw != dst {
			fmt.Fprintf(buf, "%s%s := %s\n", indent, dst, intCast(p.goType, raw))
		}
	default:
		if goConvertFromString(p, dst) == dst {
			fmt.Fprintf(buf, "%s%s, err := asString(%s)\n", indent, dst, src)
			fmt.Fprintf(buf, fail, label)
			return
		}
		raw := dst + "s"
		fmt.Fprintf(buf, "%s%s, err := asString(%s)\n", indent, raw, src)
		fmt.Fprintf(buf, fail, label)
		fmt.Fprintf(buf, "%s%s := %s\n", indent, dst, goConvertFromString(p, raw))
	}
}

func writeScalarCall(buf *bytes.Buffer, s *setter, raw string) {
	p := s.goParams[0]
	buf.WriteString("\t\t")
	switch {
	case p.goType == "ocispec.Platform":
		fmt.Fprintf(buf, "p, err := asPlatform(%s)\n", raw)
		buf.WriteString("\t\tif err != nil {\n")
		fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", s.prop+": %w")
		buf.WriteString("\t\t} else {\n")
		fmt.Fprintf(buf, "\t\t\topts = append(opts, %s(p))\n", s.name)
		buf.WriteString("\t\t}\n")
	case p.goType == "bool" || p.tsType == "boolean":
		fmt.Fprintf(buf, "b, err := asBool(%s)\n", raw)
		buf.WriteString("\t\tif err != nil {\n")
		fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", s.prop+": %w")
		buf.WriteString("\t\t} else {\n")
		fmt.Fprintf(buf, "\t\t\topts = append(opts, %s(b))\n", s.name)
		buf.WriteString("\t\t}\n")
	case p.goType == "time.Duration" || p.tsType == "number | string":
		fmt.Fprintf(buf, "d, err := asDuration(%s)\n", raw)
		buf.WriteString("\t\tif err != nil {\n")
		fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", s.prop+": %w")
		buf.WriteString("\t\t} else {\n")
		fmt.Fprintf(buf, "\t\t\topts = append(opts, %s(d))\n", s.name)
		buf.WriteString("\t\t}\n")
	case strings.Contains(p.tsType, "number") || isIntGoType(p.goType):
		fmt.Fprintf(buf, "n, err := asInt(%s)\n", raw)
		buf.WriteString("\t\tif err != nil {\n")
		fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", s.prop+": %w")
		buf.WriteString("\t\t} else if err := fitInt(n, ")
		fmt.Fprintf(buf, "%q); err != nil {\n", p.goType)
		fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", s.prop+": %w")
		buf.WriteString("\t\t} else {\n")
		fmt.Fprintf(buf, "\t\t\topts = append(opts, %s(%s))\n", s.name, goConvertFromInt(p))
		buf.WriteString("\t\t}\n")
	case p.variadic:
		fmt.Fprintf(buf, "ss, err := asStringSlice(%s)\n", raw)
		buf.WriteString("\t\tif err != nil {\n")
		fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", s.prop+": %w")
		buf.WriteString("\t\t} else {\n")
		fmt.Fprintf(buf, "\t\t\topts = append(opts, %s(ss...))\n", s.name)
		buf.WriteString("\t\t}\n")
	default:
		fmt.Fprintf(buf, "s, err := asString(%s)\n", raw)
		buf.WriteString("\t\tif err != nil {\n")
		fmt.Fprintf(buf, "\t\t\terrs = append(errs, fmt.Errorf(%q, err))\n", s.prop+": %w")
		buf.WriteString("\t\t} else {\n")
		fmt.Fprintf(buf, "\t\t\topts = append(opts, %s(%s))\n", s.name, goConvertFromString(p, "s"))
		buf.WriteString("\t\t}\n")
	}
}

func isIntGoType(goType string) bool {
	switch goType {
	case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64":
		return true
	default:
		return false
	}
}

func intCast(goType, expr string) string {
	switch goType {
	case "", "int":
		return expr
	default:
		return goType + "(" + expr + ")"
	}
}

func goConvertFromString(p goParam, expr string) string {
	switch p.goType {
	case "", "string", "T":
		return expr
	case "[]byte", "[]uint8":
		return "[]byte(" + expr + ")"
	case "scheme.Mode":
		return "scheme.Mode(" + expr + ")"
	default:
		if strings.Contains(p.goType, ".") {
			return p.goType + "(" + expr + ")"
		}
		if len(p.goType) == 1 {
			return expr
		}
		if p.goType != "" && p.goType != "string" {
			return p.goType + "(" + expr + ")"
		}
		return expr
	}
}

func goConvertFromInt(p goParam) string {
	switch p.goType {
	case "int", "":
		return "n"
	default:
		return p.goType + "(n)"
	}
}

func writeDecodeAction(buf *bytes.Buffer, verbs []verb) {
	buf.WriteString("func decodeActionOptions(op string, v any) error {\n")
	buf.WriteString("\tswitch op {\n")
	seen := map[string]bool{}
	for _, v := range verbs {
		if v.bag == "" || seen[v.op] {
			continue
		}
		seen[v.op] = true
		fmt.Fprintf(buf, "\tcase %q:\n", v.op)
		fmt.Fprintf(buf, "\t\t_, err := decode%s(v)\n", v.bag)
		buf.WriteString("\t\treturn err\n")
	}
	buf.WriteString("\tdefault:\n")
	buf.WriteString("\t\treturn nil\n")
	buf.WriteString("\t}\n")
	buf.WriteString("}\n\n")
}

func writeExec(buf *bytes.Buffer, verbs []verb) {
	buf.WriteString("func execKnownAction(ctx context.Context, cli *Client, compose *Compose, act planAction) ([]byte, error) {\n")
	buf.WriteString("\tswitch act.Op {\n")
	seen := map[string]bool{}
	for _, v := range verbs {
		if v.op == "" || seen[v.op] || (v.bag == "" && !v.bare) {
			continue
		}
		seen[v.op] = true
		fmt.Fprintf(buf, "\tcase %q:\n", v.op)
		buf.WriteString("\t\t{\n")
		if v.needsYAML {
			fmt.Fprintf(buf, "\t\t\tif compose == nil {\n\t\t\t\treturn nil, fmt.Errorf(\"tsx plan: yaml required for %s\")\n\t\t\t}\n", v.op)
		}
		if v.bag != "" {
			fmt.Fprintf(buf, "\t\t\topts, err := decode%s(act.Options)\n", v.bag)
			buf.WriteString("\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n")
		}
		writeExecCall(buf, v)
		buf.WriteString("\t\t}\n")
	}
	buf.WriteString("\tdefault:\n")
	buf.WriteString("\t\treturn nil, fmt.Errorf(\"tsx plan: unknown op %q\", act.Op)\n")
	buf.WriteString("\t}\n")
	buf.WriteString("}\n")
}

func writeExecCall(buf *bytes.Buffer, v verb) {
	writePosPrelude(buf, v)
	call := callExpr(v)
	n := len(v.results)
	switch {
	case n == 2 && v.results[1] == "error" && v.results[0] == "Loaded":
		fmt.Fprintf(buf, "\t\t\tloaded, err := %s\n", call)
		buf.WriteString("\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n")
		buf.WriteString("\t\t\tname := \"\"\n")
		buf.WriteString("\t\t\tif loaded != nil && loaded.Project != nil {\n\t\t\t\tname = loaded.Project.Name\n\t\t\t}\n")
		buf.WriteString("\t\t\treturn marshalLoose(map[string]string{\"name\": name})\n")
	case n >= 2 && v.results[n-1] == "error":
		vars := make([]string, 0, n)
		for i := 0; i < n-1; i++ {
			vars = append(vars, fmt.Sprintf("out%d", i))
		}
		vars = append(vars, "err")
		fmt.Fprintf(buf, "\t\t\t%s := %s\n", strings.Join(vars, ", "), call)
		buf.WriteString("\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n")
		if n == 2 {
			buf.WriteString("\t\t\treturn marshalLoose(out0)\n")
			return
		}
		parts := make([]string, 0, n-1)
		for i := 0; i < n-1; i++ {
			parts = append(parts, fmt.Sprintf("out%d", i))
		}
		fmt.Fprintf(buf, "\t\t\treturn marshalLoose([]any{%s})\n", strings.Join(parts, ", "))
	case n == 1 && v.results[0] == "error":
		fmt.Fprintf(buf, "\t\t\tif err := %s; err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n", call)
		buf.WriteString("\t\t\treturn []byte(`{\"ok\":true}`), nil\n")
	case n == 1:
		fmt.Fprintf(buf, "\t\t\treturn marshalLoose(%s)\n", call)
	default:
		fmt.Fprintf(buf, "\t\t\t%s\n", call)
		buf.WriteString("\t\t\treturn []byte(`{\"ok\":true}`), nil\n")
	}
}

func callExpr(v verb) string {
	var b strings.Builder
	switch v.recv {
	case "":
		b.WriteString(v.goName)
	case "Client":
		b.WriteString("cli.")
		b.WriteString(v.goName)
	case "Compose":
		b.WriteString("compose.")
		b.WriteString(v.goName)
	case "Container":
		b.WriteString("NewContainer().")
		b.WriteString(v.goName)
	default:
		b.WriteString("/* unsupported receiver ")
		b.WriteString(v.recv)
		b.WriteString(" */ ")
		b.WriteString(v.goName)
	}
	b.WriteByte('(')
	for i, s := range v.slots {
		if i > 0 {
			b.WriteString(", ")
		}
		switch s.kind {
		case "ctx":
			b.WriteString("ctx")
		case "engine":
			b.WriteString("cli.Engine()")
		case "composer":
			b.WriteString("cli.Composer()")
		case "compose":
			b.WriteString("compose")
		case "opts":
			b.WriteString("opts...")
		case "pos":
			b.WriteString(fmt.Sprintf("pos%d", i))
		default:
			b.WriteString("nil")
		}
	}
	b.WriteByte(')')
	return b.String()
}

func writePosPrelude(buf *bytes.Buffer, v verb) {
	for i, s := range v.slots {
		if s.kind != "pos" {
			continue
		}
		writePosAssign(buf, i, s)
	}
}

func writePosAssign(buf *bytes.Buffer, i int, s callSlot) {
	name := fmt.Sprintf("pos%d", i)
	label := s.name
	if label == "" {
		label = name
	}
	format := label + ": %w"
	switch s.goType {
	case "", "string":
		fmt.Fprintf(buf, "\t\t\t%s := act.fieldString(%q)\n", name, s.name)
	case "[]string":
		fmt.Fprintf(buf, "\t\t\t%s, err := asStringSlice(act.fields[%q])\n", name, s.name)
		fmt.Fprintf(buf, "\t\t\tif err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, err)\n\t\t\t}\n", format)
	case "time.Duration":
		fmt.Fprintf(buf, "\t\t\t%s, err := asDuration(act.fieldString(%q))\n", name, s.name)
		fmt.Fprintf(buf, "\t\t\tif err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, err)\n\t\t\t}\n", format)
	case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64":
		fmt.Fprintf(buf, "\t\t\t%sN, err := act.fieldInt(%q)\n", name, s.name)
		fmt.Fprintf(buf, "\t\t\tif err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, err)\n\t\t\t}\n", format)
		fmt.Fprintf(buf, "\t\t\tif err := fitInt(%sN, %q); err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, err)\n\t\t\t}\n", name, s.goType, format)
		fmt.Fprintf(buf, "\t\t\t%s := %s\n", name, intCast(s.goType, name+"N"))
	default:
		if strings.HasPrefix(s.goType, "[]") {
			fmt.Fprintf(buf, "\t\t\t%sRaw, err := asStringSlice(act.fields[%q])\n", name, s.name)
			fmt.Fprintf(buf, "\t\t\tif err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, err)\n\t\t\t}\n", format)
			fmt.Fprintf(buf, "\t\t\t%s := %s(%sRaw)\n", name, s.goType, name)
			return
		}
		fmt.Fprintf(buf, "\t\t\t%s := %s(act.fieldString(%q))\n", name, s.goType, s.name)
	}
}
