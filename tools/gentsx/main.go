type setter struct {
	name        string
	kind        string
	propScope   string
	ret         string
	nested      bool
	nestedIface string
	leaf        bool
	prop        string
	tsType      string
	doc         string
	scopes      map[string]bool
	actionBags  map[string]bool
	variadic    bool
	jsonSkip    bool
	fields      []leadParam
	goParams    []goParam
}

type leadParam struct {
	name   string
	tsType string
	goType string
}

type goParam struct {
	name     string
	tsType   string
	goType   string
	variadic bool
	skip     bool
}

type bagInfo struct {
	tsName string
	iface  string
	apply  string
}

type callSlot struct {
	kind   string
	name   string
	goType string
}

type verb struct {
	tsName      string
	op          string
	goName      string
	bag         string
	iface       string
	recv        string
	needsYAML   bool
	engine      bool
	bare        bool
	positionals []leadParam
	slots       []callSlot
	results     []string
}

func main() {
	root, err := moduleRoot()
	if err != nil {
		fatal(err)
	}

	fset := token.NewFileSet()
	files, err := parseKit(fset, filepath.Join(root, "pkg", "kit"))
	if err != nil {
		fatal(err)
	}

	optionKind := map[string]string{}
	retApplies := map[string]map[string]bool{}
	setters := map[string]*setter{}
	applyBag := map[string]string{}
	bags := map[string]*bagInfo{}
	optionIfaces := map[string]bool{}
	typeDocs := map[string]string{}

	for _, file := range files {
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				if d.Tok != token.TYPE {
					continue
				}
				for _, spec := range d.Specs {
					ts, ok := spec.(*ast.TypeSpec)
					if !ok {
						continue
					}
					if doc := typeDoc(d, ts); doc != "" && typeDocs[ts.Name.Name] == "" {
						typeDocs[ts.Name.Name] = doc
					}
					iface, ok := ts.Type.(*ast.InterfaceType)
					if !ok || iface.Methods == nil {
						continue
					}
					for _, m := range iface.Methods.List {
						if m.Names == nil {
							continue
						}
						for _, id := range m.Names {
							if !strings.HasPrefix(id.Name, "apply") {
								continue
							}
							optionIfaces[ts.Name.Name] = true
							if kind, ok := defineApply[id.Name]; ok {
								optionKind[ts.Name.Name] = kind
							} else if optionKind[ts.Name.Name] == "" {
								base := strings.TrimSuffix(ts.Name.Name, "Option")
								optionKind[ts.Name.Name] = jsIdent(base)
							}
							bname := bagTSName(ts.Name.Name)
							applyBag[id.Name] = bname
							if bags[bname] == nil {
								bags[bname] = &bagInfo{tsName: bname, iface: ts.Name.Name, apply: id.Name}
							}
						}
					}
				}
			case *ast.FuncDecl:
				if d.Name == nil || d.Recv == nil {
					continue
				}
				recv := recvName(d.Recv)
				if recv == "" || recv == "Grouped" {
					continue
				}
				if !strings.HasPrefix(d.Name.Name, "apply") {
					continue
				}
				if retApplies[recv] == nil {
					retApplies[recv] = map[string]bool{}
				}
				retApplies[recv][d.Name.Name] = true
			}
		}
	}

	for _, file := range files {
		for _, decl := range file.Decls {
			d, ok := decl.(*ast.FuncDecl)
			if !ok || d.Name == nil || d.Recv != nil {
				continue
			}
			if !d.Name.IsExported() || skipFuncs[d.Name.Name] || d.Type.Results == nil || len(d.Type.Results.List) != 1 {
				continue
			}
			ret := typeName(d.Type.Results.List[0].Type)
			if ret == "" {
				continue
			}
			s := classify(d.Name.Name, d.Type.Params, optionKind, optionIfaces)
			s.name = d.Name.Name
			s.doc = commentText(d.Doc)
			s.ret = ret
			rewriteGenericParams(s, d.Type.TypeParams)
			setters[d.Name.Name] = s
		}
	}

	for n, s := range setters {
		for applyName := range retApplies[s.ret] {
			if kind, ok := defineApply[applyName]; ok {
				if s.scopes == nil {
					s.scopes = map[string]bool{}
				}
				s.scopes[kind] = true
			}
			if bag, ok := applyBag[applyName]; ok {
				if s.actionBags == nil {
					s.actionBags = map[string]bool{}
				}
				s.actionBags[bag] = true
			}
		}
		if len(s.scopes) == 0 && len(s.actionBags) == 0 {
			delete(setters, n)
		}
	}

	verbs := parseVerbs(files, bags)

	nestedByScope := map[string][]string{}
	leafByScope := map[string][]string{}
	propsByScope := map[string][]*setter{}
	leadByKind := map[string]*setter{}
	leafFields := map[string][]leadParam{}
	propAlias := map[string]string{}
	identByKind := map[string]string{}
	for k, v := range extraIdent {
		identByKind[k] = v
	}

	var nested, leafs []*setter
	seenN, seenL := map[string]bool{}, map[string]bool{}

	names := make([]string, 0, len(setters))
	for n := range setters {
		names = append(names, n)
	}
	sort.Strings(names)

	for _, n := range names {
		s := setters[n]
		switch {
		case s.nested:
			if !seenN[s.kind] {
				nested = append(nested, s)
				seenN[s.kind] = true
			}
			identByKind[s.kind] = s.name
			if s.propScope != "" && s.propScope != s.kind {
				propAlias[s.kind] = s.propScope
			}
			if s.prop != "" {
				leadByKind[s.kind] = s
			}
			for sc := range s.scopes {
				nestedByScope[sc] = appendUnique(nestedByScope[sc], s.kind)
			}
		case s.leaf:
			if !seenL[s.kind] {
				leafs = append(leafs, s)
				seenL[s.kind] = true
			}
			identByKind[s.kind] = s.name
			if len(s.fields) > 0 {
				leafFields[s.kind] = s.fields
			}
			for sc := range s.scopes {
				leafByScope[sc] = appendUnique(leafByScope[sc], s.kind)
			}
		default:
			// A Logger, reader, or callback cannot ride in the plan JSON.
			// Leaving it on the props as unknown would accept any value.
			if s.jsonSkip {
				break
			}
			for sc := range s.scopes {
				propsByScope[sc] = append(propsByScope[sc], s)
			}
		}
	}

	for sc, kids := range extra {
		for _, k := range kids {
			nestedByScope[sc] = appendUnique(nestedByScope[sc], k)
		}
	}

	allKinds := append([]string{}, roots...)
	for _, s := range nested {
		allKinds = appendUnique(allKinds, s.kind)
	}
	for _, s := range leafs {
		allKinds = appendUnique(allKinds, s.kind)
	}
	for _, kids := range extra {
		for _, k := range kids {
			allKinds = appendUnique(allKinds, k)
		}
	}
	sort.Strings(allKinds)

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// %s\n\n", generatedBy)
	buf.WriteString("import { element, type MaybeChild, type Node } from \"./node.js\";\n")
	buf.WriteString("import { resolveEnv, resolveNamedValue, type EnvInput } from \"./env.js\";\n")
	buf.WriteString("import type { DockerfileNode } from \"./docker-file.js\";\n\n")
	writeJSDoc(&buf, "", "Child list and element shape used by every component in this file.\n\n@see {@link MaybeChild}\n@see {@link Node}")
	buf.WriteString("export type { MaybeChild, Node };\n\n")

	kindSet := map[string]bool{"fragment": true}
	for _, k := range allKinds {
		kindSet[k] = true
	}
	var kindList []string
	for k := range kindSet {
		kindList = append(kindList, k)
	}
	sort.Strings(kindList)
	writeJSDoc(&buf, "", "Element kind stored on `$$kind`.\n\n@remarks\n`fragment` is a list of elements. Every other name is a component in this file.")
	buf.WriteString("export type Kind =\n")
	for i, k := range kindList {
		if i == len(kindList)-1 {
			fmt.Fprintf(&buf, "\t| %q;\n\n", k)
			continue
		}
		fmt.Fprintf(&buf, "\t| %q\n", k)
	}

	parentsOf := map[string][]string{}
	for _, k := range allKinds {
		kids := mergedKids(k, propAlias, nestedByScope, leafByScope)
		if k == "build" {
			kids = appendUnique(kids, "dockerfile")
		}
		parent := identOf(identByKind, k)
		for _, kid := range kids {
			parentsOf[kid] = appendUnique(parentsOf[kid], parent)
		}
	}
	for _, names := range parentsOf {
		sort.Strings(names)
	}

	for _, k := range allKinds {
		if k == "fragment" {
			continue
		}
		ident := identOf(identByKind, k)
		doc := componentDoc(ident, k, setters, typeDocs, parentsOf[k], listedProps(k, propAlias, leadByKind, leafFields, propsByScope))
		writeJSDoc(&buf, "", doc)
		fmt.Fprintf(&buf, "export type %sProps = {\n", ident)
		seenProp := map[string]bool{}
		for _, src := range propSources(k, propAlias) {
			if lead, ok := leadByKind[src]; ok && lead.prop != "" && !seenProp[lead.prop] {
				seenProp[lead.prop] = true
				writeJSDoc(&buf, "\t", propDoc(lead))
				fmt.Fprintf(&buf, "\t%s?: %s;\n", lead.prop, lead.tsType)
			}
			for _, f := range leafFields[src] {
				if f.name == "" || seenProp[f.name] {
					continue
				}
				seenProp[f.name] = true
				fmt.Fprintf(&buf, "\t%s?: %s;\n", f.name, f.tsType)
			}
		}
		ps := mergedProps(k, propAlias, propsByScope)
		sort.Slice(ps, func(i, j int) bool { return ps[i].prop < ps[j].prop })
		for _, s := range ps {
			if s.prop == "" || seenProp[s.prop] {
				continue
			}
			seenProp[s.prop] = true
			writeJSDoc(&buf, "\t", propDoc(s))
			fmt.Fprintf(&buf, "\t%s?: %s;\n", s.prop, s.tsType)
		}
		kids := mergedKids(k, propAlias, nestedByScope, leafByScope)
		if k == "build" {
			kids = append(kids, "dockerfile")
		}
		if k == "env" || k == "label" {
			buf.WriteString("\tchildren?: string;\n")
		} else if len(kids) == 0 {
			buf.WriteString("\tchildren?: MaybeChild<never>;\n")
		} else {
			fmt.Fprintf(&buf, "\tchildren?: MaybeChild<%s>;\n", childUnion(identByKind, kids))
		}
		buf.WriteString("};\n\n")
		// The node props are the component props without children. Children are
		// stored on the node, not on props. P still has to extend the full props
		// type so DockerNode<Compose<{ name?: string }>> accepts a compose node.
		writeJSDoc(&buf, "", fmt.Sprintf("A %s element.\n\n@remarks\nProps are {@link %sProps} without `children`. Nested elements are stored on the node.", ident, ident))
		fmt.Fprintf(&buf, "export type %s<P extends %sProps = Omit<%sProps, \"children\">> = Node<%q, P>;\n", ident, ident, ident, k)
		writeJSDoc(&buf, "", fmt.Sprintf("%s when it is the child of another element.", ident))
		fmt.Fprintf(&buf, "export type %sNode = %s;\n\n", ident, ident)
	}

	for _, k := range allKinds {
		if k == "fragment" {
			continue
		}
		ident := identOf(identByKind, k)
		fnDoc := withSignature(componentDoc(ident, k, setters, typeDocs, parentsOf[k], listedProps(k, propAlias, leadByKind, leafFields, propsByScope)), ident)
		writeJSDoc(&buf, "", fnDoc)
		switch k {
		case "env":
			buf.WriteString("export function Env(props: EnvInput): Env<{ name?: string; value: string }> {\n")
			buf.WriteString("\treturn element(\"env\", resolveEnv(props));\n")
			buf.WriteString("}\n\n")
			continue
		case "label":
			buf.WriteString("export function Label(props: EnvInput): Label<{ name?: string; value: string }> {\n")
			buf.WriteString("\treturn element(\"label\", resolveNamedValue(props, \"label\"));\n")
			buf.WriteString("}\n\n")
			continue
		}
		fmt.Fprintf(&buf, "export function %s(props: %sProps): %s {\n", ident, ident, ident)
		fmt.Fprintf(&buf, "\treturn element(%q, props);\n", k)
		buf.WriteString("}\n\n")
	}

	kidsByKind := map[string][]string{}
	for _, k := range allKinds {
		kids := mergedKids(k, propAlias, nestedByScope, leafByScope)
		if k == "build" {
			kids = append(kids, "dockerfile")
			sort.Strings(kids)
			kids = unique(kids)
		}
		kidsByKind[k] = kids
	}
	dfInstr := dockerfileInstructions(filepath.Join(root, "tsx", "src", "docker-file.ts"))
	for _, k := range dfInstr {
		kidsByKind[k] = nil
	}
	kidsByKind["dockerfile"] = dfInstr

	var kindKeys []string
	for k := range kidsByKind {
		kindKeys = append(kindKeys, k)
	}
	sort.Strings(kindKeys)
	writeJSDoc(&buf, "", "Child element kinds each parent kind accepts.\n\n@remarks\nThe eslint plugin and the renderer both read this map. A kind that is not listed is not valid inside that parent.")
	buf.WriteString("export const allowedChildren: Record<string, readonly string[]> = {\n")
	for _, k := range kindKeys {
		fmt.Fprintf(&buf, "\t%q: [%s],\n", k, quoteList(kidsByKind[k]))
	}
	buf.WriteString("};\n\n")

	onceKind := onceKinds(files, setters)
	dfGroups := dockerfileOnce(files, dfInstr)
	writeJSDoc(&buf, "", "Children that may appear only once inside a parent.\n\n@remarks\n`message` is the error reported when a second child of that kind is present.")
	buf.WriteString("export const singleChildren: Record<string, readonly { kinds: readonly string[]; message: string }[]> = {\n")
	for _, parent := range kindKeys {
		var groups []singleGroup
		for _, kid := range kidsByKind[parent] {
			if !onceKind[kid] {
				continue
			}
			groups = append(groups, singleGroup{
				kinds:   []string{kid},
				message: fmt.Sprintf("<%s> is already set inside <%s>", kid, parent),
			})
		}
		if parent == "build" {
			groups = append(groups, singleGroup{
				kinds:   []string{"dockerfile"},
				message: "Build accepts one Dockerfile, and not alongside dockerfilePath, parseDockerfile, or readDockerfile",
			})
		}
		if parent == "dockerfile" {
			groups = append(groups, dfGroups...)
		}
		if len(groups) == 0 {
			continue
		}
		sort.Slice(groups, func(i, j int) bool { return groups[i].kinds[0] < groups[j].kinds[0] })
		fmt.Fprintf(&buf, "\t%q: [\n", parent)
		for _, g := range groups {
			fmt.Fprintf(&buf, "\t\t{ kinds: [%s], message: %q },\n", quoteList(g.kinds), g.message)
		}
		buf.WriteString("\t],\n")
	}
	buf.WriteString("};\n\n")
	writeJSDoc(&buf, "", "Props that cannot be set on a parent when a given child is also present.\n\n@remarks\n`message` is the error reported when both the child and one of `props` are set.")
	buf.WriteString("export const exclusiveChildProps: Record<string, { child: string; props: readonly string[]; message: string }> = {\n")
	buf.WriteString("\tbuild: {\n")
	buf.WriteString("\t\tchild: \"dockerfile\",\n")
	buf.WriteString("\t\tprops: [\"dockerfilePath\", \"parseDockerfile\", \"readDockerfile\"],\n")
	buf.WriteString("\t\tmessage: \"Build accepts one Dockerfile, and not alongside dockerfilePath, parseDockerfile, or readDockerfile\",\n")
	buf.WriteString("\t},\n")
	buf.WriteString("};\n\n")
	writeComponentMap(&buf, "composeComponents", "Compose component name to element kind.\n\n@remarks\n`Dockerfile` and `BuildArg` are hand-written and included here so one map covers every Compose component.", composeComponentKinds(allKinds, identByKind))
	writeComponentMap(&buf, "dockerfileComponents", "Dockerfile instruction name to element kind.", dockerfileComponentKinds(filepath.Join(root, "tsx", "src", "docker-file.ts")))

	out := filepath.Join(root, "tsx", "src", "generated.ts")
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(out, buf.Bytes(), 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("wrote %s (%d setters)\n", out, len(setters))

	if err := writeOptions(root, setters, bags); err != nil {
		fatal(err)
	}
	if err := writeActions(root, verbs); err != nil {
		fatal(err)
	}
	if err := writePlanGo(root, setters, bags, verbs); err != nil {
		fatal(err)
	}
}

func classify(name string, fields *ast.FieldList, optionKind map[string]string, optionIfaces map[string]bool) *setter {
	s := &setter{name: name, prop: jsIdent(name), tsType: "unknown", kind: jsIdent(name), goParams: collectGoParams(fields)}
	s.jsonSkip = paramsSkipJSON(s.goParams)
	if fields == nil || len(fields.List) == 0 {
		s.tsType = "boolean"
		return s
	}
	last := fields.List[len(fields.List)-1]
	if ell, ok := last.Type.(*ast.Ellipsis); ok {
		tn := typeName(ell.Elt)
		if optionIfaces[tn] {
			s.nested = true
			s.nestedIface = tn
			s.prop = ""
			s.tsType = ""
			s.kind = jsIdent(name)
			s.jsonSkip = false
			if k, ok := optionKind[tn]; ok {
				s.propScope = k
			} else {
				s.propScope = s.kind
			}
			if lead := leadingParam(fields); lead != nil {
				s.prop = lead.name
				s.tsType = lead.tsType
			}
			return s
		}
		nlead := 0
		for _, f := range fields.List {
			n := len(f.Names)
			if n == 0 {
				n = 1
			}
			nlead += n
		}
		if nlead >= 2 {
			s.leaf = true
			s.fields = paramFields(fields)
			s.prop = ""
			s.tsType = ""
			return s
		}
		s.variadic = true
		s.tsType = "string | string[]"
		return s
	}
	nparams := 0
	for _, f := range fields.List {
		n := len(f.Names)
		if n == 0 {
			n = 1
		}
		nparams += n
	}
	if nparams >= 2 {
		s.leaf = true
		s.fields = paramFields(fields)
		s.prop = ""
		s.tsType = ""
		return s
	}
	s.tsType = tsType(last.Type)
	return s
}

func leadingParam(fields *ast.FieldList) *leadParam {
	if fields == nil || len(fields.List) < 2 {
		return nil
	}
	f := fields.List[0]
	n := "value"
	if len(f.Names) > 0 {
		n = f.Names[0].Name
	}
	return &leadParam{name: jsxPropName(n), tsType: tsType(f.Type)}
}

func paramFields(fields *ast.FieldList) []leadParam {
	if fields == nil {
		return nil
	}
	var out []leadParam
	for _, f := range fields.List {
		names := f.Names
		if len(names) == 0 {
			out = append(out, leadParam{name: "value", tsType: tsType(f.Type)})
			continue
		}
		for _, id := range names {
			out = append(out, leadParam{name: jsxPropName(id.Name), tsType: tsType(f.Type)})
		}
	}
	return out
}

func jsxPropName(n string) string {
	switch n {
	case "key":
		return "name"
	case "type":
		return "kind"
	default:
		return jsIdent(n)
	}
}

func tsType(expr ast.Expr) string {
	switch x := expr.(type) {
	case *ast.Ident:
		switch x.Name {
		case "string":
			return "string"
		case "bool":
			return "boolean"
		case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "byte", "rune":
			return "number"
		case "float32", "float64":
			return "number"
		default:
			if u, ok := vocabType(x.Name); ok {
				return u
			}
			return "string"
		}
	case *ast.SelectorExpr:
		if u, ok := vocabType(typeName(x)); ok {
			return u
		}
		if id, ok := x.X.(*ast.Ident); ok && id.Name == "time" && x.Sel.Name == "Duration" {
			return "number | string"
		}
		return "string"
	case *ast.IndexExpr:
		return "string"
	case *ast.ArrayType:
		if id, ok := x.Elt.(*ast.Ident); ok && (id.Name == "byte" || id.Name == "uint8") {
			return "string"
		}
		return "string[]"
	case *ast.Ellipsis:
		return "string | string[]"
	default:
		return "unknown"
	}
}

func typeName(expr ast.Expr) string {
	switch x := expr.(type) {
	case *ast.Ident:
		return x.Name
	case *ast.StarExpr:
		return typeName(x.X)
	case *ast.ArrayType:
		return "[]" + typeName(x.Elt)
	case *ast.SelectorExpr:
		if id, ok := x.X.(*ast.Ident); ok {
			return id.Name + "." + x.Sel.Name
		}
		return x.Sel.Name
	case *ast.IndexExpr:
		return typeName(x.X)
	case *ast.IndexListExpr:
		return typeName(x.X)
	default:
		return ""
	}
}

func recvName(fl *ast.FieldList) string {
	if fl == nil || len(fl.List) == 0 {
		return ""
	}
	return typeName(fl.List[0].Type)
}

func jsIdent(s string) string {
	runes := []rune(s)
	if len(runes) == 0 {
		return s
	}
	i := 0
	for i < len(runes) && unicode.IsUpper(runes[i]) {
		i++
	}
	if i == 0 {
		return s
	}
	if i == len(runes) {
		return strings.ToLower(s)
	}
	if i == 1 {
		runes[0] = unicode.ToLower(runes[0])
		return string(runes)
	}
	rest := runes[i:]
	if len(rest) == 1 && unicode.IsLower(rest[0]) {
		return strings.ToLower(s)
	}
	if len(rest) >= 2 && unicode.IsLower(rest[0]) && unicode.IsDigit(rest[1]) {
		for j := 0; j < i; j++ {
			runes[j] = unicode.ToLower(runes[j])
		}
		return string(runes)
	}
	for j := 0; j < i-1; j++ {
		runes[j] = unicode.ToLower(runes[j])
	}
	return string(runes)
}

var docLink = regexp.MustCompile(`\[([A-Za-z0-9_./]+)\]`)

func commentText(g *ast.CommentGroup) string {
	if g == nil {
		return ""
	}
	text := strings.TrimSpace(g.Text())
	text = docLink.ReplaceAllString(text, "$1")
	return strings.ReplaceAll(text, "*/", "* /")
}

func typeDoc(d *ast.GenDecl, ts *ast.TypeSpec) string {
	if ts != nil && ts.Doc != nil {
		return commentText(ts.Doc)
	}
	if d != nil && d.Doc != nil && len(d.Specs) == 1 {
		return commentText(d.Doc)
	}
	return ""
}

type docProp struct {
	name   string
	tsType string
}

func listedProps(kind string, alias map[string]string, leads map[string]*setter, leaves map[string][]leadParam, props map[string][]*setter) []docProp {
	var out []docProp
	seen := map[string]bool{}
	add := func(name, tsType string) {
		if name == "" || seen[name] || tsType == "" {
			return
		}
		seen[name] = true
		out = append(out, docProp{name: name, tsType: tsType})
	}
	for _, src := range propSources(kind, alias) {
		if lead, ok := leads[src]; ok {
			add(lead.prop, lead.tsType)
		}
		for _, f := range leaves[src] {
			add(f.name, f.tsType)
		}
	}
	ps := mergedProps(kind, alias, props)
	sort.Slice(ps, func(i, j int) bool { return ps[i].prop < ps[j].prop })
	for _, s := range ps {
		add(s.prop, s.tsType)
	}
	return out
}

func componentDoc(ident, kind string, setters map[string]*setter, typeDocs map[string]string, parents []string, props []docProp) string {
	doc := ""
	if s := setters[ident]; s != nil && s.doc != "" {
		doc = s.doc
	} else if d := typeDocs[ident]; d != "" {
		doc = d
	} else {
		doc = fmt.Sprintf("%s is the %s scope as a TSX component.", ident, kind)
	}
	if len(parents) > 0 && !strings.Contains(doc, "Parent:") {
		doc += "\n\nParent: " + strings.Join(parents, ", ")
	}
	if !strings.Contains(doc, "@example") {
		doc += "\n\n@example\n```tsx\n" + exampleTag(ident, props) + "\n```"
	}
	return doc
}

func exampleTag(ident string, props []docProp) string {
	byName := map[string]docProp{}
	for _, p := range props {
		byName[p.name] = p
	}
	var chosen []docProp
	for _, name := range []string{"name", "image", "test", "source", "target", "path", "port", "policy", "driver", "value", "interval", "hostPort", "containerPort"} {
		if p, ok := byName[name]; ok {
			chosen = append(chosen, p)
		}
		if len(chosen) == 3 {
			break
		}
	}
	if len(chosen) == 0 {
		for _, p := range props {
			chosen = append(chosen, p)
			if len(chosen) == 2 {
				break
			}
		}
	}
	if len(chosen) == 0 {
		return "<" + ident + " />"
	}
	attrs := make([]string, len(chosen))
	for i, p := range chosen {
		attrs[i] = p.name + "=" + exampleValue(p.name, p.tsType)
	}
	return "<" + ident + " " + strings.Join(attrs, " ") + " />"
}

func exampleValue(name, tsType string) string {
	switch name {
	case "name":
		return `"app"`
	case "image":
		return `"alpine"`
	case "test":
		return `{["CMD", "true"]}`
	case "source":
		return `"."`
	case "target":
		return `"/data"`
	case "path":
		return `"/tmp"`
	case "port", "containerPort":
		return `{80}`
	case "hostPort":
		return `{8080}`
	case "policy":
		return `"unless-stopped"`
	case "driver":
		return `"bridge"`
	case "value":
		if strings.HasPrefix(tsType, "number") && !strings.Contains(tsType, "string") {
			return "{1}"
		}
		return `"1"`
	case "interval", "timeout", "startPeriod":
		return `"30s"`
	}
	if strings.Contains(tsType, "boolean") && !strings.Contains(tsType, "|") {
		return "{true}"
	}
	if strings.HasPrefix(tsType, "number") {
		if strings.Contains(tsType, "string") {
			return `"30s"`
		}
		return "{1}"
	}
	if i := strings.Index(tsType, `"`); i >= 0 {
		rest := tsType[i+1:]
		if j := strings.Index(rest, `"`); j >= 0 {
			return `"` + rest[:j] + `"`
		}
	}
	if strings.Contains(tsType, "string[]") {
		return `{["example"]}`
	}
	return `"example"`
}

func propDoc(s *setter) string {
	if s == nil {
		return ""
	}
	if !isDuration(s) {
		return s.doc
	}
	const note = "A number is nanoseconds. A string is a Go duration such as \"30s\"."
	if s.doc == "" {
		return note
	}
	return s.doc + "\n" + note
}

func isDuration(s *setter) bool {
	if s.tsType != "number | string" {
		return false
	}
	for _, p := range s.goParams {
		if p.goType == "time.Duration" {
			return true
		}
	}
	return false
}

func withSignature(doc, ident string) string {
	sig := "@param props - Props for this element. Nested elements are children, not fields of this object.\n@returns The " + ident + " element."
	if i := strings.Index(doc, "\n@example"); i >= 0 {
		return doc[:i] + "\n" + sig + doc[i:]
	}
	return doc + "\n\n" + sig
}

func writeJSDoc(buf *bytes.Buffer, indent, doc string) {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return
	}
	lines := strings.Split(doc, "\n")
	if len(lines) == 1 {
		fmt.Fprintf(buf, "%s/** %s */\n", indent, lines[0])
		return
	}
	fmt.Fprintf(buf, "%s/**\n", indent)
	for _, line := range lines {
		if strings.TrimSpace(line) == "" {
			fmt.Fprintf(buf, "%s *\n", indent)
			continue
		}
		fmt.Fprintf(buf, "%s * %s\n", indent, strings.TrimRight(line, " \t"))
	}
	fmt.Fprintf(buf, "%s */\n", indent)
}

func identOf(idents map[string]string, kind string) string {
	if s := idents[kind]; s != "" {
		return s
	}
	r, size := utf8.DecodeRuneInString(kind)
	return string(unicode.ToUpper(r)) + kind[size:]
}

func propSources(kind string, alias map[string]string) []string {
	out := []string{kind}
	if a := alias[kind]; a != "" && a != kind {
		out = append(out, a)
	}
	return out
}

func mergedProps(kind string, alias map[string]string, props map[string][]*setter) []*setter {
	var out []*setter
	for _, src := range propSources(kind, alias) {
		out = append(out, props[src]...)
	}
	return out
}

func mergedKids(kind string, alias map[string]string, nested, leaf map[string][]string) []string {
	var kids []string
	for _, src := range propSources(kind, alias) {
		kids = append(kids, nested[src]...)
		kids = append(kids, leaf[src]...)
	}
	sort.Strings(kids)
	return unique(kids)
}

func childUnion(idents map[string]string, kids []string) string {
	parts := make([]string, 0, len(kids)+1)
	for _, k := range kids {
		parts = append(parts, identOf(idents, k)+"Node")
	}
	parts = append(parts, `Node<"fragment">`)
	return strings.Join(parts, " | ")
}

func appendUnique(in []string, v string) []string {
	for _, x := range in {
		if x == v {
			return in
		}
	}
	return append(in, v)
}

func unique(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, v := range in {
		if seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, v)
	}
	return out
}

type singleGroup struct {
	kinds   []string
	message string
}

func onceKinds(files []*ast.File, setters map[string]*setter) map[string]bool {
	card := map[string]struct{ single, many bool }{}
	for _, file := range files {
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv == nil || fn.Body == nil {
				continue
			}
			recv := recvName(fn.Recv)
			if !strings.HasSuffix(recv, "Opt") {
				continue
			}
			single, many := optStores(fn)
			c := card[recv]
			c.single = c.single || single
			c.many = c.many || many
			card[recv] = c
		}
	}
	once := map[string]bool{}
	for _, s := range setters {
		if !s.nested && !s.leaf {
			continue
		}
		c := card[s.ret]
		if c.single && !c.many {
			once[s.kind] = true
		}
	}
	return once
}

func optStores(fn *ast.FuncDecl) (single, many bool) {
	acc := map[string]bool{}
	for _, stmt := range fn.Body.List {
		ds, ok := stmt.(*ast.DeclStmt)
		if !ok {
			continue
		}
		g, ok := ds.Decl.(*ast.GenDecl)
		if !ok || g.Tok != token.VAR {
			continue
		}
		for _, spec := range g.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok || !isAccumulatorType(vs.Type) {
				continue
			}
			for _, name := range vs.Names {
				acc[name.Name] = true
			}
		}
	}
	ast.Inspect(fn.Body, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		name := callName(call.Fun)
		switch {
		case name == "append" && appendsValue(call):
			many = true
		case isSetter(name, "add"):
			many = true
		case isSetter(name, "set"):
			single = true
		case name == "assign" && callPasses(call, acc):
			single = true
		}
		return true
	})
	return single, many
}

func isAccumulatorType(expr ast.Expr) bool {
	id, ok := expr.(*ast.Ident)
	if !ok {
		return false
	}
	switch id.Name {
	case "string", "bool", "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"float32", "float64", "byte", "rune", "error", "any":
		return false
	default:
		return id.Name != ""
	}
}

func isSetter(name, prefix string) bool {
	if !strings.HasPrefix(name, prefix) || len(name) == len(prefix) {
		return false
	}
	r, _ := utf8.DecodeRuneInString(name[len(prefix):])
	return unicode.IsUpper(r)
}

func callPasses(call *ast.CallExpr, acc map[string]bool) bool {
	for _, arg := range call.Args {
		id, ok := arg.(*ast.Ident)
		if ok && acc[id.Name] {
			return true
		}
	}
	return false
}

func appendsValue(call *ast.CallExpr) bool {
	if len(call.Args) < 2 {
		return false
	}
	switch arg := call.Args[0].(type) {
	case *ast.Ident:
		return arg.Name != "errs" && arg.Name != "err"
	case *ast.StarExpr:
		id, ok := arg.X.(*ast.Ident)
		return ok && id.Name != "errs" && id.Name != "err"
	case *ast.SelectorExpr:
		return arg.Sel.Name != "errs"
	default:
		return false
	}
}

func callName(fun ast.Expr) string {
	switch x := fun.(type) {
	case *ast.Ident:
		return x.Name
	case *ast.SelectorExpr:
		return x.Sel.Name
	default:
		return ""
	}
}

func composeComponentKinds(kinds []string, idents map[string]string) map[string]string {
	out := map[string]string{}
	for _, kind := range kinds {
		name := identOf(idents, kind)
		if prev, ok := out[name]; ok && prev != kind {
			fatal(fmt.Sprintf("component %s is both %s and %s", name, prev, kind))
		}
		out[name] = kind
	}
	// These two are hand-written and re-exported from the package root.
	out["Dockerfile"] = "dockerfile"
	out["BuildArg"] = "env"
	return out
}

func dockerfileComponentKinds(path string) map[string]string {
	b, err := os.ReadFile(path)
	if err != nil {
		fatal(err)
	}
	text := string(b)
	out := map[string]string{"Dockerfile": "dockerfile"}
	add := func(name, kind string) {
		if prev, ok := out[name]; ok && prev != kind {
			fatal(fmt.Sprintf("dockerfile component %s is both %s and %s", name, prev, kind))
		}
		out[name] = kind
	}
	for _, m := range regexp.MustCompile(`export const (\w+) = instr<"(\w+)"`).FindAllStringSubmatch(text, -1) {
		add(m[1], m[2])
	}
	for _, m := range regexp.MustCompile(`export function (\w+)\([^)]*\): Node<"(\w+)"`).FindAllStringSubmatch(text, -1) {
		add(m[1], m[2])
	}
	return out
}

func writeComponentMap(buf *bytes.Buffer, name, doc string, kinds map[string]string) {
	keys := make([]string, 0, len(kinds))
	for key := range kinds {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	writeJSDoc(buf, "", doc)
	fmt.Fprintf(buf, "export const %s: Record<string, string> = {\n", name)
	for _, key := range keys {
		fmt.Fprintf(buf, "\t%q: %q,\n", key, kinds[key])
	}
	buf.WriteString("};\n\n")
}

