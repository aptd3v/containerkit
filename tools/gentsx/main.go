type setter struct {
	name        string
	kind        string
	propScope   string
	ret         string
	nested      bool
	nestedIface string
	leaf        bool
	prop        string
	tsType      string
	scopes      map[string]bool
	actionBags  map[string]bool
	variadic    bool
	jsonSkip    bool
	fields      []leadParam
	goParams    []goParam
}

type leadParam struct {
	name   string
	tsType string
	goType string
}

type goParam struct {
	name     string
	tsType   string
	goType   string
	variadic bool
	skip     bool
}

type bagInfo struct {
	tsName string
	iface  string
	apply  string
}

type callSlot struct {
	kind   string
	name   string
	goType string
}

type verb struct {
	tsName      string
	op          string
	goName      string
	bag         string
	iface       string
	recv        string
	needsYAML   bool
	engine      bool
	positionals []leadParam
	slots       []callSlot
	results     []string
}

func main() {
	root, err := moduleRoot()
	if err != nil {
		fatal(err)
	}

	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, filepath.Join(root, "pkg", "kit"), func(info os.FileInfo) bool {
		n := info.Name()
		return strings.HasSuffix(n, ".go") && !strings.HasSuffix(n, "_test.go")
	}, 0)
	if err != nil {
		fatal(err)
	}
	pkg := pkgs["kit"]
	if pkg == nil {
		fatal("package kit not found")
	}

	optionKind := map[string]string{}
	retApplies := map[string]map[string]bool{}
	setters := map[string]*setter{}
	applyBag := map[string]string{}
	bags := map[string]*bagInfo{}
	optionIfaces := map[string]bool{}

	for _, file := range pkg.Files {
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				if d.Tok != token.TYPE {
					continue
				}
				for _, spec := range d.Specs {
					ts, ok := spec.(*ast.TypeSpec)
					if !ok {
						continue
					}
					iface, ok := ts.Type.(*ast.InterfaceType)
					if !ok || iface.Methods == nil {
						continue
					}
					for _, m := range iface.Methods.List {
						if m.Names == nil {
							continue
						}
						for _, id := range m.Names {
							if !strings.HasPrefix(id.Name, "apply") {
								continue
							}
							optionIfaces[ts.Name.Name] = true
							if kind, ok := defineApply[id.Name]; ok {
								optionKind[ts.Name.Name] = kind
							} else if optionKind[ts.Name.Name] == "" {
								base := strings.TrimSuffix(ts.Name.Name, "Option")
								optionKind[ts.Name.Name] = jsIdent(base)
							}
							bname := bagTSName(ts.Name.Name)
							applyBag[id.Name] = bname
							if bags[bname] == nil {
								bags[bname] = &bagInfo{tsName: bname, iface: ts.Name.Name, apply: id.Name}
							}
						}
					}
				}
			case *ast.FuncDecl:
				if d.Name == nil || d.Recv == nil {
					continue
				}
				recv := recvName(d.Recv)
				if recv == "" || recv == "Grouped" {
					continue
				}
				if !strings.HasPrefix(d.Name.Name, "apply") {
					continue
				}
				if retApplies[recv] == nil {
					retApplies[recv] = map[string]bool{}
				}
				retApplies[recv][d.Name.Name] = true
			}
		}
	}

	for _, file := range pkg.Files {
		for _, decl := range file.Decls {
			d, ok := decl.(*ast.FuncDecl)
			if !ok || d.Name == nil || d.Recv != nil {
				continue
			}
			if !d.Name.IsExported() || skipFuncs[d.Name.Name] || d.Type.Results == nil || len(d.Type.Results.List) != 1 {
				continue
			}
			ret := typeName(d.Type.Results.List[0].Type)
			if ret == "" {
				continue
			}
			s := classify(d.Name.Name, d.Type.Params, optionKind, optionIfaces)
			s.name = d.Name.Name
			s.ret = ret
			rewriteGenericParams(s, d.Type.TypeParams)
			setters[d.Name.Name] = s
		}
	}

	for n, s := range setters {
		for applyName := range retApplies[s.ret] {
			if kind, ok := defineApply[applyName]; ok {
				if s.scopes == nil {
					s.scopes = map[string]bool{}
				}
				s.scopes[kind] = true
			}
			if bag, ok := applyBag[applyName]; ok {
				if s.actionBags == nil {
					s.actionBags = map[string]bool{}
				}
				s.actionBags[bag] = true
			}
		}
		if len(s.scopes) == 0 && len(s.actionBags) == 0 {
			delete(setters, n)
		}
	}

	verbs := parseVerbs(pkg, bags)

	nestedByScope := map[string][]string{}
	leafByScope := map[string][]string{}
	propsByScope := map[string][]*setter{}
	leadByKind := map[string]*setter{}
	leafFields := map[string][]leadParam{}
	propAlias := map[string]string{}
	identByKind := map[string]string{}
	for k, v := range extraIdent {
		identByKind[k] = v
	}

	var nested, leafs []*setter
	seenN, seenL := map[string]bool{}, map[string]bool{}

	names := make([]string, 0, len(setters))
	for n := range setters {
		names = append(names, n)
	}
	sort.Strings(names)

	for _, n := range names {
		s := setters[n]
		switch {
		case s.nested:
			if !seenN[s.kind] {
				nested = append(nested, s)
				seenN[s.kind] = true
			}
			identByKind[s.kind] = s.name
			if s.propScope != "" && s.propScope != s.kind {
				propAlias[s.kind] = s.propScope
			}
			if s.prop != "" {
				leadByKind[s.kind] = s
			}
			for sc := range s.scopes {
				nestedByScope[sc] = appendUnique(nestedByScope[sc], s.kind)
			}
		case s.leaf:
			if !seenL[s.kind] {
				leafs = append(leafs, s)
				seenL[s.kind] = true
			}
			identByKind[s.kind] = s.name
			if len(s.fields) > 0 {
				leafFields[s.kind] = s.fields
			}
			for sc := range s.scopes {
				leafByScope[sc] = appendUnique(leafByScope[sc], s.kind)
			}
		default:
			for sc := range s.scopes {
				propsByScope[sc] = append(propsByScope[sc], s)
			}
		}
	}

	for sc, kids := range extra {
		for _, k := range kids {
			nestedByScope[sc] = appendUnique(nestedByScope[sc], k)
		}
	}

	allKinds := append([]string{}, roots...)
	for _, s := range nested {
		allKinds = appendUnique(allKinds, s.kind)
	}
	for _, s := range leafs {
		allKinds = appendUnique(allKinds, s.kind)
	}
	for _, kids := range extra {
		for _, k := range kids {
			allKinds = appendUnique(allKinds, k)
		}
	}
	sort.Strings(allKinds)

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// %s\n\n", generatedBy)
	buf.WriteString("import { element, type MaybeChild, type Node } from \"./node.js\";\n")
	buf.WriteString("import { resolveEnv, resolveNamedValue, type EnvInput } from \"./env.js\";\n")
	buf.WriteString("import type { DockerfileNode } from \"./docker-file.js\";\n\n")
	buf.WriteString("export type { MaybeChild, Node };\n\n")

	kindSet := map[string]bool{"fragment": true}
	for _, k := range allKinds {
		kindSet[k] = true
	}
	var kindList []string
	for k := range kindSet {
		kindList = append(kindList, k)
	}
	sort.Strings(kindList)
	buf.WriteString("export type Kind =\n")
	for i, k := range kindList {
		if i == len(kindList)-1 {
			fmt.Fprintf(&buf, "\t| %q;\n\n", k)
			continue
		}
		fmt.Fprintf(&buf, "\t| %q\n", k)
	}

	for _, k := range allKinds {
		if k == "fragment" {
			continue
		}
		ident := identOf(identByKind, k)
		fmt.Fprintf(&buf, "export type %sProps = {\n", ident)
		seenProp := map[string]bool{}
		for _, src := range propSources(k, propAlias) {
			if lead, ok := leadByKind[src]; ok && lead.prop != "" && !seenProp[lead.prop] {
				seenProp[lead.prop] = true
				fmt.Fprintf(&buf, "\t%s?: %s;\n", lead.prop, lead.tsType)
			}
			for _, f := range leafFields[src] {
				if f.name == "" || seenProp[f.name] {
					continue
				}
				seenProp[f.name] = true
				fmt.Fprintf(&buf, "\t%s?: %s;\n", f.name, f.tsType)
			}
		}
		ps := mergedProps(k, propAlias, propsByScope)
		sort.Slice(ps, func(i, j int) bool { return ps[i].prop < ps[j].prop })
		for _, s := range ps {
			if s.prop == "" || seenProp[s.prop] {
				continue
			}
			seenProp[s.prop] = true
			fmt.Fprintf(&buf, "\t%s?: %s;\n", s.prop, s.tsType)
		}
		kids := mergedKids(k, propAlias, nestedByScope, leafByScope)
		if k == "build" {
			kids = append(kids, "dockerfile")
		}
		if k == "env" || k == "label" {
			buf.WriteString("\tchildren?: string;\n")
		} else if len(kids) == 0 {
			buf.WriteString("\tchildren?: MaybeChild<never>;\n")
		} else {
			fmt.Fprintf(&buf, "\tchildren?: MaybeChild<%s>;\n", childUnion(identByKind, kids))
		}
		buf.WriteString("};\n\n")
		// The node props are the component props without children. Children are
		// stored on the node, not on props. P still has to extend the full props
		// type so DockerNode<Compose<{ name?: string }>> accepts a compose node.
		fmt.Fprintf(&buf, "export type %s<P extends %sProps = Omit<%sProps, \"children\">> = Node<%q, P>;\n", ident, ident, ident, k)
		fmt.Fprintf(&buf, "export type %sNode = %s;\n\n", ident, ident)
	}

	for _, k := range allKinds {
		if k == "fragment" {
			continue
		}
		ident := identOf(identByKind, k)
		fmt.Fprintf(&buf, "// %s is the kit %s scope as a TSX component.\n", ident, k)
		switch k {
		case "env":
			buf.WriteString("export function Env(props: EnvInput): Env<{ name?: string; value: string }> {\n")
			buf.WriteString("\treturn element(\"env\", resolveEnv(props));\n")
			buf.WriteString("}\n\n")
			continue
		case "label":
			buf.WriteString("export function Label(props: EnvInput): Label<{ name?: string; value: string }> {\n")
			buf.WriteString("\treturn element(\"label\", resolveNamedValue(props, \"label\"));\n")
			buf.WriteString("}\n\n")
			continue
		}
		fmt.Fprintf(&buf, "export function %s(props: %sProps): %s {\n", ident, ident, ident)
		fmt.Fprintf(&buf, "\treturn element(%q, props);\n", k)
		buf.WriteString("}\n\n")
	}

	buf.WriteString("export const allowedChildren: Record<string, readonly string[]> = {\n")
	scopes := make([]string, 0, len(nestedByScope)+len(leafByScope))
	seenSc := map[string]bool{}
	for sc := range nestedByScope {
		scopes = append(scopes, sc)
		seenSc[sc] = true
	}
	for sc := range leafByScope {
		if !seenSc[sc] {
			scopes = append(scopes, sc)
		}
	}
	sort.Strings(scopes)
	for _, sc := range scopes {
		kids := mergedKids(sc, propAlias, nestedByScope, leafByScope)
		if sc == "build" {
			kids = append(kids, "dockerfile")
		}
		fmt.Fprintf(&buf, "\t%q: [%s],\n", sc, quoteList(kids))
	}
	buf.WriteString("};\n")

	out := filepath.Join(root, "tsx", "src", "generated.ts")
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(out, buf.Bytes(), 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("wrote %s (%d setters)\n", out, len(setters))

	if err := writeOptions(root, setters, bags); err != nil {
		fatal(err)
	}
	if err := writeActions(root, verbs); err != nil {
		fatal(err)
	}
	if err := writePlanGo(root, setters, bags, verbs); err != nil {
		fatal(err)
	}
}

func classify(name string, fields *ast.FieldList, optionKind map[string]string, optionIfaces map[string]bool) *setter {
	s := &setter{name: name, prop: jsIdent(name), tsType: "unknown", kind: jsIdent(name), goParams: collectGoParams(fields)}
	s.jsonSkip = paramsSkipJSON(s.goParams)
	if fields == nil || len(fields.List) == 0 {
		s.tsType = "boolean"
		return s
	}
	last := fields.List[len(fields.List)-1]
	if ell, ok := last.Type.(*ast.Ellipsis); ok {
		tn := typeName(ell.Elt)
		if optionIfaces[tn] {
			s.nested = true
			s.nestedIface = tn
			s.prop = ""
			s.tsType = ""
			s.kind = jsIdent(name)
			s.jsonSkip = false
			if k, ok := optionKind[tn]; ok {
				s.propScope = k
			} else {
				s.propScope = s.kind
			}
			if lead := leadingParam(fields); lead != nil {
				s.prop = lead.name
				s.tsType = lead.tsType
			}
			return s
		}
		nlead := 0
		for _, f := range fields.List {
			n := len(f.Names)
			if n == 0 {
				n = 1
			}
			nlead += n
		}
		if nlead >= 2 {
			s.leaf = true
			s.fields = paramFields(fields)
			s.prop = ""
			s.tsType = ""
			return s
		}
		s.variadic = true
		s.tsType = "string | string[]"
		return s
	}
	nparams := 0
	for _, f := range fields.List {
		n := len(f.Names)
		if n == 0 {
			n = 1
		}
		nparams += n
	}
	if nparams >= 2 {
		s.leaf = true
		s.fields = paramFields(fields)
		s.prop = ""
		s.tsType = ""
		return s
	}
	s.tsType = tsType(last.Type)
	return s
}

func leadingParam(fields *ast.FieldList) *leadParam {
	if fields == nil || len(fields.List) < 2 {
		return nil
	}
	f := fields.List[0]
	n := "value"
	if len(f.Names) > 0 {
		n = f.Names[0].Name
	}
	return &leadParam{name: jsxPropName(n), tsType: tsType(f.Type)}
}

func paramFields(fields *ast.FieldList) []leadParam {
	if fields == nil {
		return nil
	}
	var out []leadParam
	for _, f := range fields.List {
		names := f.Names
		if len(names) == 0 {
			out = append(out, leadParam{name: "value", tsType: tsType(f.Type)})
			continue
		}
		for _, id := range names {
			out = append(out, leadParam{name: jsxPropName(id.Name), tsType: tsType(f.Type)})
		}
	}
	return out
}

func jsxPropName(n string) string {
	switch n {
	case "key":
		return "name"
	case "type":
		return "kind"
	default:
		return jsIdent(n)
	}
}

func tsType(expr ast.Expr) string {
	switch x := expr.(type) {
	case *ast.Ident:
		switch x.Name {
		case "string":
			return "string"
		case "bool":
			return "boolean"
		case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "byte", "rune":
			return "number"
		case "float32", "float64":
			return "number"
		default:
			return "string"
		}
	case *ast.SelectorExpr:
		if id, ok := x.X.(*ast.Ident); ok && id.Name == "time" && x.Sel.Name == "Duration" {
			return "number | string"
		}
		return "string"
	case *ast.IndexExpr:
		return "string"
	case *ast.ArrayType:
		if id, ok := x.Elt.(*ast.Ident); ok && (id.Name == "byte" || id.Name == "uint8") {
			return "string"
		}
		return "string[]"
	case *ast.Ellipsis:
		return "string | string[]"
	default:
		return "unknown"
	}
}

func typeName(expr ast.Expr) string {
	switch x := expr.(type) {
	case *ast.Ident:
		return x.Name
	case *ast.StarExpr:
		return typeName(x.X)
	case *ast.ArrayType:
		return "[]" + typeName(x.Elt)
	case *ast.SelectorExpr:
		if id, ok := x.X.(*ast.Ident); ok {
			return id.Name + "." + x.Sel.Name
		}
		return x.Sel.Name
	case *ast.IndexExpr:
		return typeName(x.X)
	case *ast.IndexListExpr:
		return typeName(x.X)
	default:
		return ""
	}
}

func recvName(fl *ast.FieldList) string {
	if fl == nil || len(fl.List) == 0 {
		return ""
	}
	return typeName(fl.List[0].Type)
}

func jsIdent(s string) string {
	runes := []rune(s)
	if len(runes) == 0 {
		return s
	}
	i := 0
	for i < len(runes) && unicode.IsUpper(runes[i]) {
		i++
	}
	if i == 0 {
		return s
	}
	if i == len(runes) {
		return strings.ToLower(s)
	}
	if i == 1 {
		runes[0] = unicode.ToLower(runes[0])
		return string(runes)
	}
	rest := runes[i:]
	if len(rest) == 1 && unicode.IsLower(rest[0]) {
		return strings.ToLower(s)
	}
	if len(rest) >= 2 && unicode.IsLower(rest[0]) && unicode.IsDigit(rest[1]) {
		for j := 0; j < i; j++ {
			runes[j] = unicode.ToLower(runes[j])
		}
		return string(runes)
	}
	for j := 0; j < i-1; j++ {
		runes[j] = unicode.ToLower(runes[j])
	}
	return string(runes)
}

func identOf(idents map[string]string, kind string) string {
	if s := idents[kind]; s != "" {
		return s
	}
	r, size := utf8.DecodeRuneInString(kind)
	return string(unicode.ToUpper(r)) + kind[size:]
}

func propSources(kind string, alias map[string]string) []string {
	out := []string{kind}
	if a := alias[kind]; a != "" && a != kind {
		out = append(out, a)
	}
	return out
}

func mergedProps(kind string, alias map[string]string, props map[string][]*setter) []*setter {
	var out []*setter
	for _, src := range propSources(kind, alias) {
		out = append(out, props[src]...)
	}
	return out
}

func mergedKids(kind string, alias map[string]string, nested, leaf map[string][]string) []string {
	var kids []string
	for _, src := range propSources(kind, alias) {
		kids = append(kids, nested[src]...)
		kids = append(kids, leaf[src]...)
	}
	sort.Strings(kids)
	return unique(kids)
}

func childUnion(idents map[string]string, kids []string) string {
	parts := make([]string, 0, len(kids)+1)
	for _, k := range kids {
		parts = append(parts, identOf(idents, k)+"Node")
	}
	parts = append(parts, `Node<"fragment">`)
	return strings.Join(parts, " | ")
}

func appendUnique(in []string, v string) []string {
	for _, x := range in {
		if x == v {
			return in
		}
	}
	return append(in, v)
}

func unique(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, v := range in {
		if seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, v)
	}
	return out
}

func quoteList(in []string) string {
	parts := make([]string, len(in))
	for i, s := range in {
		parts[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(parts, ", ")
}

func moduleRoot() (string, error) {
	root, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
			return root, nil
		}
		parent := filepath.Dir(root)
		if parent == root {
			return "", fmt.Errorf("go.mod not found")
		}
		root = parent
	}
}

func fatal(v any) {
	fmt.Fprintln(os.Stderr, v)
	os.Exit(1)
}
