// Command gencatalog extracts exported types from the Docker Engine API,
// Engine client, Compose-Go, Compose v5 API, and adjacent Docker modules,
// then writes documented type aliases into internal/<domain>/types.
//
// Each upstream package maps to its own domain package so original type
// names are preserved without collision prefixes.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const generatedBy = "Code generated by go run ./tools/gencatalog; DO NOT EDIT."

type TypeDecl struct {
	ImportPath string
	PkgName    string
	Name       string
	Exported   bool
	Kind       string
	Doc        string
	Expr       string
	TypeParams string
	File       string
	RelFile    string
	Line       int
	Refs       []string
}

type root struct {
	Module     string
	Rel        string
	ImportPath string
	Recursive  bool
	SkipDirs   map[string]bool
	Dir        string
}

func main() {
	modDirs := moduleDirs()

	roots := []root{
		{Module: "github.com/moby/moby/api", Rel: "types", ImportPath: "github.com/moby/moby/api/types", Recursive: true},
		{Module: "github.com/moby/moby/api", Rel: "pkg", ImportPath: "github.com/moby/moby/api/pkg", Recursive: true},
		{Module: "github.com/moby/moby/client", Rel: "", ImportPath: "github.com/moby/moby/client"},
		{Module: "github.com/moby/moby/client", Rel: "pkg", ImportPath: "github.com/moby/moby/client/pkg", Recursive: true},
		{
			Module: "github.com/compose-spec/compose-go/v2", Rel: "", ImportPath: "github.com/compose-spec/compose-go/v2",
			Recursive: true,
			SkipDirs:  map[string]bool{"internal": true, "cmd": true, "ci": true, "scripts": true, "fixtures": true},
		},
		{Module: "github.com/docker/compose/v5", Rel: "pkg/api", ImportPath: "github.com/docker/compose/v5/pkg/api"},
		{Module: "github.com/docker/go-connections", Rel: "", ImportPath: "github.com/docker/go-connections", Recursive: true},
		{Module: "github.com/docker/go-units", Rel: "", ImportPath: "github.com/docker/go-units"},
		{Module: "github.com/opencontainers/go-digest", Rel: "", ImportPath: "github.com/opencontainers/go-digest"},
		{Module: "github.com/opencontainers/image-spec", Rel: "specs-go/v1", ImportPath: "github.com/opencontainers/image-spec/specs-go/v1"},
		{Module: "github.com/moby/docker-image-spec", Rel: "specs-go/v1", ImportPath: "github.com/moby/docker-image-spec/specs-go/v1"},
		{Module: "github.com/distribution/reference", Rel: "", ImportPath: "github.com/distribution/reference"},
	}

	var decls []*TypeDecl
	for _, r := range roots {
		dir, ok := modDirs[r.Module]
		if !ok {
			fatalf("module %s is not in go.mod / module cache", r.Module)
		}
		r.Dir = filepath.Join(dir, filepath.FromSlash(r.Rel))
		if r.Rel == "" {
			r.Dir = dir
		}
		ds, err := extractRoot(r)
		if err != nil {
			fatalf("extract %s: %v", r.ImportPath, err)
		}
		decls = append(decls, ds...)
	}

	sort.Slice(decls, func(i, j int) bool {
		if decls[i].ImportPath != decls[j].ImportPath {
			return decls[i].ImportPath < decls[j].ImportPath
		}
		return decls[i].Name < decls[j].Name
	})
	decls = unique(decls)

	removeGenerated("internal")
	removeGenerated("pkg/types")
	_ = os.Remove("pkg/types/catalog_test.go")

	byOut := map[string][]*TypeDecl{}
	unexportedByOut := map[string][]*TypeDecl{}
	for _, d := range decls {
		out, skip, err := outDir(d.ImportPath)
		if skip {
			continue
		}
		if err != nil {
			if !d.Exported {
				continue
			}
			fatalf("%v", err)
		}
		if d.Exported {
			byOut[out] = append(byOut[out], d)
			continue
		}
		unexportedByOut[out] = append(unexportedByOut[out], d)
	}

	outs := make([]string, 0, len(byOut))
	for out := range byOut {
		outs = append(outs, out)
	}
	sort.Strings(outs)

	var exported, unexported int
	for _, out := range outs {
		chosen := uniqueByName(byOut[out])
		exported += len(chosen)
		unexp := unexportedByOut[out]
		unexported += len(unexp)
		if err := writePackage(out, chosen, unexp); err != nil {
			fatalf("write %s: %v", out, err)
		}
		fmt.Printf("wrote %s (%d types)\n", out, len(chosen))
	}

	fmt.Printf("total named types: %d (exported %d, unexported listed %d) across %d packages\n",
		len(decls), exported, unexported, len(outs))
}

func moduleDirs() map[string]string {
	cmd := exec.Command("go", "list", "-m", "-f", "{{.Path}}\t{{.Dir}}", "all")
	out, err := cmd.Output()
	if err != nil {
		fatalf("go list -m: %v", err)
	}
	dirs := map[string]string{}
	for _, line := range strings.Split(string(out), "\n") {
		path, dir, ok := strings.Cut(line, "\t")
		if !ok || dir == "" || dir == "-" {
			continue
		}
		dirs[path] = dir
	}
	return dirs
}

func outDir(importPath string) (string, bool, error) {
	switch {
	case importPath == "github.com/compose-spec/compose-go/v2/types":
		return "internal/compose/types", false, nil
	case importPath == "github.com/compose-spec/compose-go/v2":
		return "", true, nil
	case strings.HasPrefix(importPath, "github.com/compose-spec/compose-go/v2/"):
		rest := strings.TrimPrefix(importPath, "github.com/compose-spec/compose-go/v2/")
		return "internal/compose/" + rest + "/types", false, nil
	case importPath == "github.com/docker/compose/v5/pkg/api":
		return "internal/compose/api/types", false, nil
	case importPath == "github.com/moby/moby/client":
		return "internal/client/types", false, nil
	case strings.HasPrefix(importPath, "github.com/moby/moby/client/pkg/"):
		rest := strings.TrimPrefix(importPath, "github.com/moby/moby/client/pkg/")
		return "internal/client/" + rest + "/types", false, nil
	case importPath == "github.com/moby/moby/api/types":
		return "internal/engine/types", false, nil
	case strings.HasPrefix(importPath, "github.com/moby/moby/api/types/"):
		rest := strings.TrimPrefix(importPath, "github.com/moby/moby/api/types/")
		return "internal/engine/" + rest + "/types", false, nil
	case strings.HasPrefix(importPath, "github.com/moby/moby/api/pkg/"):
		rest := strings.TrimPrefix(importPath, "github.com/moby/moby/api/pkg/")
		return "internal/engine/" + rest + "/types", false, nil
	case importPath == "github.com/docker/go-connections":
		return "", true, nil
	case strings.HasPrefix(importPath, "github.com/docker/go-connections/"):
		rest := strings.TrimPrefix(importPath, "github.com/docker/go-connections/")
		return "internal/connections/" + rest + "/types", false, nil
	case importPath == "github.com/docker/go-units":
		return "internal/units/types", false, nil
	case importPath == "github.com/opencontainers/go-digest":
		return "internal/digest/types", false, nil
	case importPath == "github.com/opencontainers/image-spec/specs-go/v1":
		return "internal/oci/types", false, nil
	case importPath == "github.com/moby/docker-image-spec/specs-go/v1":
		return "internal/imagespec/types", false, nil
	case importPath == "github.com/distribution/reference":
		return "internal/reference/types", false, nil
	default:
		return "", false, fmt.Errorf("no internal/<domain>/types mapping for %s", importPath)
	}
}

func extractRoot(r root) ([]*TypeDecl, error) {
	if !r.Recursive {
		return extractDir(r.Dir, r.ImportPath)
	}
	var out []*TypeDecl
	err := filepath.WalkDir(r.Dir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		base := filepath.Base(path)
		if path != r.Dir && (strings.HasPrefix(base, ".") || base == "testdata" || base == "fixtures" || base == "internal" || r.SkipDirs[base]) {
			return filepath.SkipDir
		}
		rel, err := filepath.Rel(r.Dir, path)
		if err != nil {
			return err
		}
		ip := r.ImportPath
		if rel != "." {
			ip = r.ImportPath + "/" + filepath.ToSlash(rel)
		}
		ds, err := extractDir(path, ip)
		if err != nil {
			return err
		}
		out = append(out, ds...)
		return nil
	})
	return out, err
}

func extractDir(dir, importPath string) ([]*TypeDecl, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(info os.FileInfo) bool {
		name := info.Name()
		return strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go")
	}, parser.ParseComments)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var out []*TypeDecl
	seen := map[string]bool{}
	for pkgName, pkg := range pkgs {
		if strings.HasSuffix(pkgName, "_test") {
			continue
		}
		files := make([]*ast.File, 0, len(pkg.Files))
		for _, f := range pkg.Files {
			files = append(files, f)
		}
		sort.Slice(files, func(i, j int) bool {
			return fset.File(files[i].Pos()).Name() < fset.File(files[j].Pos()).Name()
		})
		for _, f := range files {
			imports := importMap(f)
			filename := fset.File(f.Pos()).Name()
			rel := filepath.Base(filename)
			for _, decl := range f.Decls {
				gd, ok := decl.(*ast.GenDecl)
				if !ok || gd.Tok != token.TYPE {
					continue
				}
				for _, spec := range gd.Specs {
					ts := spec.(*ast.TypeSpec)
					key := pkgName + "." + ts.Name.Name
					if seen[key] {
						continue
					}
					seen[key] = true
					doc := ts.Doc
					if doc == nil {
						doc = gd.Doc
					}
					out = append(out, &TypeDecl{
						ImportPath: importPath,
						PkgName:    pkgName,
						Name:       ts.Name.Name,
						Exported:   ast.IsExported(ts.Name.Name),
						Kind:       kindOf(ts.Type),
						Doc:        strings.TrimSpace(docText(doc)),
						Expr:       exprString(ts.Type),
						TypeParams: typeParamString(ts),
						File:       filename,
						RelFile:    rel,
						Line:       fset.Position(ts.Pos()).Line,
						Refs:       collectRefs(ts.Type, imports),
					})
				}
			}
		}
	}
	return out, nil
}

func writePackage(outDir string, exported, unexported []*TypeDecl) error {
	if len(exported) == 0 {
		return nil
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	srcPkg := exported[0].ImportPath
	pkgURL := "https://pkg.go.dev/" + srcPkg

	var doc bytes.Buffer
	fmt.Fprintf(&doc, "// Package types catalogs %s for wrapping by containerkit.\n", srcPkg)
	fmt.Fprintf(&doc, "//\n")
	fmt.Fprintf(&doc, "// %s\n", generatedBy)
	fmt.Fprintf(&doc, "//\n")
	fmt.Fprintf(&doc, "// Source: %s\n", pkgURL)
	fmt.Fprintf(&doc, "//\n")
	fmt.Fprintf(&doc, "// Each identifier keeps the exact upstream type name. Domain isolation\n")
	fmt.Fprintf(&doc, "// lives in the import path (%s), not in renamed aliases.\n", outDir)
	fmt.Fprintf(&doc, "package types\n")
	if err := os.WriteFile(filepath.Join(outDir, "doc.go"), doc.Bytes(), 0o644); err != nil {
		return err
	}

	src, err := renderTypes(exported, unexported)
	if err != nil {
		return err
	}
	formatted, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("gofmt: %w\n%s", err, src)
	}
	return os.WriteFile(filepath.Join(outDir, "types.go"), formatted, 0o644)
}

func renderTypes(exported, unexported []*TypeDecl) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "package types\n\n")
	fmt.Fprintf(&b, "// %s\n\n", generatedBy)

	src := exported[0]
	alias := importAlias(src.ImportPath, src.PkgName)
	if alias == src.PkgName {
		fmt.Fprintf(&b, "import %q\n", src.ImportPath)
	} else {
		fmt.Fprintf(&b, "import %s %q\n", alias, src.ImportPath)
	}

	seen := map[string]bool{}
	for _, d := range exported {
		if seen[d.Name] {
			return nil, fmt.Errorf("duplicate exact name %s in %s", d.Name, d.ImportPath)
		}
		seen[d.Name] = true
		fmt.Fprintln(&b)
		writeTypeComment(&b, d)
		if d.TypeParams != "" {
			fmt.Fprintf(&b, "type %s%s = %s.%s%s\n", d.Name, d.TypeParams, alias, d.Name, typeParamNames(d.TypeParams))
		} else {
			fmt.Fprintf(&b, "type %s = %s.%s\n", d.Name, alias, d.Name)
		}
	}

	if len(unexported) > 0 {
		fmt.Fprintf(&b, "\n/*\nUnexported named types in %s (not aliasable; listed for wrapping completeness):\n\n", src.ImportPath)
		for _, u := range unexported {
			fmt.Fprintf(&b, "  %s (%s) %s\n", u.Name, u.Kind, strings.ReplaceAll(firstSentence(u.Doc, u), "*/", "* /"))
		}
		fmt.Fprintf(&b, "*/\n")
	}
	return b.Bytes(), nil
}

func writeTypeComment(b *bytes.Buffer, d *TypeDecl) {
	fmt.Fprintf(b, "// %s wraps %s.%s.\n", d.Name, d.PkgName, d.Name)
	if d.Doc != "" {
		fmt.Fprintf(b, "//\n")
		for _, line := range strings.Split(strings.TrimRight(d.Doc, "\n"), "\n") {
			if strings.TrimSpace(line) == "" {
				fmt.Fprintf(b, "//\n")
				continue
			}
			fmt.Fprintf(b, "// %s\n", line)
		}
	}
	fmt.Fprintf(b, "//\n")
	fmt.Fprintf(b, "// Source: https://pkg.go.dev/%s#%s\n", d.ImportPath, d.Name)
	if gh := githubURL(d); gh != "" {
		fmt.Fprintf(b, "// GitHub: %s\n", gh)
	}
	fmt.Fprintf(b, "// Kind: %s\n", d.Kind)
	if d.Expr != "" && d.Kind != "struct" && d.Kind != "interface" {
		fmt.Fprintf(b, "// Underlying: %s\n", compact(d.Expr))
	}
	if len(d.Refs) > 0 {
		fmt.Fprintf(b, "// References: %s\n", strings.Join(d.Refs, ", "))
	}
	fmt.Fprintf(b, "// Usecase: %s\n", usecase(d))
}

func importAlias(importPath, pkgName string) string {
	switch {
	case pkgName == "types":
		switch {
		case strings.Contains(importPath, "compose-go"):
			return "composetypes"
		case strings.Contains(importPath, "moby/moby/api/types"):
			return "apitypes"
		default:
			return "srctypes"
		}
	case pkgName == "v1" && strings.Contains(importPath, "docker-image-spec"):
		return "dockerspec"
	case pkgName == "v1":
		return "ocispec"
	case pkgName == "api":
		return "composeapi"
	case pkgName == "client":
		return "engineclient"
	default:
		return pkgName
	}
}

func githubURL(d *TypeDecl) string {
	switch {
	case strings.HasPrefix(d.ImportPath, "github.com/moby/moby/api"):
		rel := strings.TrimPrefix(d.ImportPath, "github.com/moby/moby/api")
		rel = strings.TrimPrefix(rel, "/")
		if rel == "" {
			return "https://github.com/moby/moby/blob/api/v1.56.1/api/" + d.RelFile
		}
		return "https://github.com/moby/moby/blob/api/v1.56.1/api/" + rel + "/" + d.RelFile
	case strings.HasPrefix(d.ImportPath, "github.com/moby/moby/client"):
		rel := strings.TrimPrefix(d.ImportPath, "github.com/moby/moby/client")
		rel = strings.TrimPrefix(rel, "/")
		if rel == "" {
			return "https://github.com/moby/moby/blob/client/v0.6.2/client/" + d.RelFile
		}
		return "https://github.com/moby/moby/blob/client/v0.6.2/client/" + rel + "/" + d.RelFile
	case strings.HasPrefix(d.ImportPath, "github.com/compose-spec/compose-go/v2"):
		rel := strings.TrimPrefix(d.ImportPath, "github.com/compose-spec/compose-go/v2")
		rel = strings.TrimPrefix(rel, "/")
		if rel == "" {
			return "https://github.com/compose-spec/compose-go/blob/v2.16.2/" + d.RelFile
		}
		return "https://github.com/compose-spec/compose-go/blob/v2.16.2/" + rel + "/" + d.RelFile
	case strings.HasPrefix(d.ImportPath, "github.com/docker/compose/v5"):
		rel := strings.TrimPrefix(d.ImportPath, "github.com/docker/compose/v5")
		rel = strings.TrimPrefix(rel, "/")
		return "https://github.com/docker/compose/blob/v5.6.1/" + rel + "/" + d.RelFile
	}
	return ""
}

func usecase(d *TypeDecl) string {
	p := d.ImportPath
	n := d.Name
	switch {
	case strings.Contains(p, "docker/compose/v5/pkg/api"):
		return "wrap the Compose runtime SDK (" + n + ") used to build/up/down/ps/logs a project."
	case strings.Contains(p, "compose-go/v2/types"):
		return "wrap the Compose file object model type " + n + "."
	case strings.Contains(p, "compose-go"):
		return "wrap compose-go " + lastSeg(p) + " machinery used while loading a Project."
	case p == "github.com/moby/moby/client":
		return "wrap the Engine client type " + n + "."
	case strings.Contains(p, "moby/moby/client/pkg"):
		return "wrap Engine client helper type " + n + "."
	case strings.Contains(p, "moby/moby/api/types"):
		return "wrap the Engine API type " + n + " from " + lastSeg(p) + "."
	case strings.Contains(p, "go-connections/nat"):
		return "wrap Docker NAT port bindings used by HostConfig.PortBindings and Compose ports."
	case strings.Contains(p, "go-connections"):
		return "wrap Docker connection helper type " + n + "."
	case strings.Contains(p, "go-units"):
		return "wrap Docker human-size/ulimit helper type " + n + "."
	case strings.Contains(p, "go-digest"):
		return "wrap an OCI content digest type used by image identity."
	case strings.Contains(p, "image-spec"):
		return "wrap an OCI/Docker image-spec type used by image inspect and manifests."
	case strings.Contains(p, "distribution/reference"):
		return "wrap a named/tagged/digested image reference."
	default:
		return "wrap " + n + " when exposing this Docker SDK surface."
	}
}

func firstSentence(doc string, d *TypeDecl) string {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return d.Name + " (" + d.Kind + ")"
	}
	doc = strings.Join(strings.Fields(strings.ReplaceAll(doc, "\n", " ")), " ")
	if i := strings.Index(doc, ". "); i > 0 {
		return doc[:i+1]
	}
	return doc
}

func lastSeg(path string) string {
	i := strings.LastIndex(path, "/")
	if i < 0 {
		return path
	}
	return path[i+1:]
}

func compact(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if len(s) > 120 {
		return s[:117] + "..."
	}
	return s
}

func removeGenerated(root string) {
	_ = filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		if !strings.HasSuffix(path, ".go") {
			return nil
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return nil
		}
		if bytes.Contains(b, []byte("Code generated by go run ./tools/gencatalog")) ||
			bytes.Contains(b, []byte("exhaustive catalog of Docker Engine SDK")) ||
			(strings.HasPrefix(path, "pkg/types/") && !strings.HasSuffix(path, "_test.go")) {
			_ = os.Remove(path)
		}
		return nil
	})
}

func unique(in []*TypeDecl) []*TypeDecl {
	seen := map[string]bool{}
	var out []*TypeDecl
	for _, d := range in {
		k := d.ImportPath + "." + d.Name
		if seen[k] {
			continue
		}
		seen[k] = true
		out = append(out, d)
	}
	return out
}

func uniqueByName(in []*TypeDecl) []*TypeDecl {
	seen := map[string]bool{}
	var out []*TypeDecl
	for _, d := range in {
		if seen[d.Name] {
			fatalf("collision on exact name %s in %s", d.Name, d.ImportPath)
		}
		seen[d.Name] = true
		out = append(out, d)
	}
	return out
}

func importMap(f *ast.File) map[string]string {
	m := map[string]string{}
	ver := regexp.MustCompile(`^v\d+$`)
	for _, im := range f.Imports {
		path, _ := strconv.Unquote(im.Path.Value)
		name := ""
		if im.Name != nil {
			name = im.Name.Name
		} else {
			parts := strings.Split(path, "/")
			name = parts[len(parts)-1]
			if strings.Contains(name, ".") {
				name = strings.Split(name, ".")[0]
			}
			if ver.MatchString(name) && len(parts) > 1 {
				name = parts[len(parts)-2]
			}
		}
		if name == "." || name == "_" {
			continue
		}
		m[name] = path
	}
	return m
}

func collectRefs(expr ast.Expr, imports map[string]string) []string {
	var refs []string
	ast.Inspect(expr, func(n ast.Node) bool {
		sel, ok := n.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		id, ok := sel.X.(*ast.Ident)
		if !ok {
			return true
		}
		if path, ok := imports[id.Name]; ok {
			refs = append(refs, path+"."+sel.Sel.Name)
		}
		return true
	})
	return uniqueStrings(refs)
}

func typeParamString(ts *ast.TypeSpec) string {
	if ts.TypeParams == nil || len(ts.TypeParams.List) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteByte('[')
	for i, f := range ts.TypeParams.List {
		if i > 0 {
			b.WriteString(", ")
		}
		for j, n := range f.Names {
			if j > 0 {
				b.WriteString(", ")
			}
			b.WriteString(n.Name)
		}
		if f.Type != nil {
			b.WriteByte(' ')
			b.WriteString(exprString(f.Type))
		}
	}
	b.WriteByte(']')
	return b.String()
}

func typeParamNames(params string) string {
	if params == "" {
		return ""
	}
	inner := strings.TrimSuffix(strings.TrimPrefix(params, "["), "]")
	var names []string
	for _, p := range strings.Split(inner, ",") {
		fields := strings.Fields(strings.TrimSpace(p))
		if len(fields) > 0 {
			names = append(names, fields[0])
		}
	}
	if len(names) == 0 {
		return ""
	}
	return "[" + strings.Join(names, ", ") + "]"
}

func kindOf(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.StructType:
		return "struct"
	case *ast.InterfaceType:
		return "interface"
	case *ast.FuncType:
		return "func"
	case *ast.ArrayType:
		return "slice"
	case *ast.MapType:
		return "map"
	case *ast.ChanType:
		return "chan"
	case *ast.Ident:
		return "named:" + e.Name
	case *ast.SelectorExpr:
		return "named:" + exprString(e)
	case *ast.StarExpr:
		return "pointer"
	case *ast.IndexExpr, *ast.IndexListExpr:
		return "generic"
	default:
		return fmt.Sprintf("%T", expr)
	}
}

func exprString(e ast.Expr) string {
	var buf bytes.Buffer
	if err := format.Node(&buf, token.NewFileSet(), e); err != nil {
		return fmt.Sprintf("%T", e)
	}
	return buf.String()
}

func docText(cg *ast.CommentGroup) string {
	if cg == nil {
		return ""
	}
	return cg.Text()
}

func uniqueStrings(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if seen[s] {
			continue
		}
		seen[s] = true
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
